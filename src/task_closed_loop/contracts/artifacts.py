from __future__ import annotations
from pathlib import Path
from typing import Any, Protocol, Sequence

class ProductionArtifactWriter(Protocol):
    def write_initial(self, candidates: Sequence[Any]) -> Path | None: ...
    def write_audited(self, tasks: Sequence[Any], *, round_number: int) -> Path | None: ...
    def write_dimensions(self, dimensions: Sequence[Any]) -> Path | None: ...
    def write_regenerated(self, candidates: Sequence[Any], *, round_number: int) -> Path | None: ...
    def write_final(self, tasks: Sequence[Any]) -> Path | None: ...
